// ============================================================
// 按代码查找一种呼吸；找不到返回空的（code 为空）
// ============================================================
BreathType BreathLib::find(const QString &code)
{
    const QVector<BreathType> list = all();
    for (const BreathType &t : list) {
        if (t.code == code) return t;
    }
    return BreathType();
}
